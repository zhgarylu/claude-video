export const GLYPH = {};
for (const k in G) GLYPH[k] = G[k].split('/');

// draw one character into a paper at tile coordinates (tx,ty): ink colour, optional 1-px shadow colour
export function putChar(paper, ch, tx, ty, ink, shadow = null) {
  const g = GLYPH[ch.toUpperCase()] || GLYPH['?'];
  if (shadow !== null) for (let y = 0; y < 7; y++) for (let x = 0; x < 5; x++) if (g[y][x] === '#') paper.px(tx * 8 + x + 1, ty * 8 + y + 1, shadow);
  for (let y = 0; y < 7; y++) for (let x = 0; x < 5; x++) if (g[y][x] === '#') paper.px(tx * 8 + x, ty * 8 + y, ink);
}
export function putText(paper, s, tx, ty, ink, shadow = null) { [...s].forEach((ch, i) => putChar(paper, ch, tx + i, ty, ink, shadow)); }
export const textW = s => s.length;
// sprite-sheet tile for a glyph (for sprite text, e.g. a bouncing score): ascii rows with ink index 1, shadow 2
export function glyphRows(ch, ink = '1', sh = '2') {
  const g = GLYPH[ch.toUpperCase()], out = Array.from({ length: 8 }, () => Array(8).fill('.'));
  for (let y = 0; y < 7; y++) for (let x = 0; x < 5; x++) if (g[y][x] === '#') out[y + 1][x + 1] = sh;
  for (let y = 0; y < 7; y++) for (let x = 0; x < 5; x++) if (g[y][x] === '#') out[y][x] = ink;
  return out.map(r => r.join(''));
}
// big logo letter: each glyph pixel becomes 2x2, outlined, 2-tone; occupies a 16x16 cell (2x2 tiles)
export function putBig(paper, ch, cx, cy, top, bottom, outline) {
  const g = GLYPH[ch.toUpperCase()]; if (!g) return;
  const set = new Set(); for (let y = 0; y < 7; y++) for (let x = 0; x < 5; x++) if (g[y][x] === '#') for (let j = 0; j < 2; j++) for (let i = 0; i < 2; i++) set.add((x * 2 + i + 2) + ',' + (y * 2 + j + 1));
  for (const k of set) { const [x, y] = k.split(',').map(Number); for (let j = -1; j <= 1; j++) for (let i = -1; i <= 1; i++) if (!set.has((x + i) + ',' + (y + j))) paper.px(cx + x + i, cy + y + j, outline); }
  for (const k of set) { const [x, y] = k.split(',').map(Number); paper.px(cx + x, cy + y, y < 8 ? top : bottom); }
}
